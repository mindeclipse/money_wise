def start_chat():
    print("="*60)
    print("🤖 Вітаємо! Я — фінансовий консультант MoneyWise.")
    print("Команди: 'вихід' (завершити), 'скинути' (очистити історію).")
    print("="*60)

    while True:
        user_input = input("\nВи: ").strip()

        if user_input.lower() in ['вихід', 'exit']:
            print("MoneyWise: До побачення!")
            break
        if user_input.lower() in ['скинути']:
            memory.clear()
            print("MoneyWise: 🔄 Контекст очищено.")
            continue
        if not user_input: continue

        try:
            logger.info(f"Запит: {user_input}")
            response = agent_executor.invoke({"input": user_input})
            print(f"\nMoneyWise: {response['output']}")
        except Exception as e:
            print(f"\n❌ Системна помилка: {str(e)}")

