@tool
def currency_converter(params: str) -> str:
    """Конвертує валюти.
    Action Input має бути рядком, де значення розділені комою: сума, з_якої_валюти, в_яку_валюту.
    Приклад Action Input: 2500, USD, UAH
    """
    logger.info(f"currency_converter отримав: {params}")
    try:
        # Розпаковуємо рядок на змінні
        parts = [p.strip() for p in params.split(',')]
        amount = float(parts[0])
        from_currency = parts[1].upper()
        to_currency = parts[2].upper()

        if amount <= 0: return "Помилка: сума повинна бути більшою за нуль."
        response = requests.get(f"https://api.exchangerate-api.com/v4/latest/{from_currency}", timeout=5)
        response.raise_for_status()
        rate = response.json()['rates'].get(to_currency)
        if not rate: return f"Помилка: Валюту {to_currency} не знайдено."
        return f"✅ {amount} {from_currency} = {amount * rate:.2f} {to_currency} (Курс: {rate})"
    except Exception as e:
        return f"Помилка при конвертації (перевірте формат даних): {str(e)}"

@tool
def loan_calculator(params: str) -> str:
    """Розраховує кредит.
    Action Input має бути рядком (через кому): сума, річна_ставка, місяці, тип(ануїтет або диференційований).
    Приклад Action Input: 100000, 20, 24, ануїтет
    """
    logger.info(f"loan_calculator отримав: {params}")
    try:
        parts = [p.strip() for p in params.split(',')]
        principal = float(parts[0])
        annual_rate = float(parts[1])
        months = int(parts[2])
        loan_type = parts[3].lower() if len(parts) > 3 else "ануїтет"

        if principal <= 0 or annual_rate < 0 or months <= 0: return "Помилка валідації."
        monthly_rate = annual_rate / 100 / 12
        if "ануїтет" in loan_type:
            payment = principal / months if monthly_rate == 0 else principal * (monthly_rate * (1 + monthly_rate)**months) / ((1 + monthly_rate)**months - 1)
            return f"💰 Ануїтет:\n- Платіж: {payment:.2f} грн\n- Переплата: {(payment * months) - principal:.2f} грн"
        elif "диференційован" in loan_type:
            pr_payment = principal / months
            return f"💰 Диференційований:\n- Перший платіж: {pr_payment + principal * monthly_rate:.2f} грн\n- Останній: {pr_payment + pr_payment * monthly_rate:.2f} грн"
        return "Невідомий тип кредиту."
    except Exception as e:
        return f"Помилка розрахунку кредиту: {str(e)}"

@tool
def savings_goal(params: str) -> str:
    """Розраховує план накопичення на мету.
    Action Input має бути рядком (через кому): цільова_сума, щомісячний_внесок, кількість_місяців, річна_ставка.
    Якщо якогось параметра немає, вкажіть 0.
    Приклад Action Input: 300000, 5000, 0, 0
    """
    logger.info(f"savings_goal отримав: {params}")
    try:
        parts = [p.strip() for p in params.split(',')]
        target_amount = float(parts[0])
        monthly_savings = float(parts[1]) if len(parts) > 1 else 0
        months_available = int(parts[2]) if len(parts) > 2 else 0
        annual_return = float(parts[3]) if len(parts) > 3 else 0

        monthly_return = annual_return / 100 / 12 if annual_return > 0 else 0
        if monthly_savings > 0 and months_available == 0:
            m_needed = target_amount / monthly_savings if monthly_return == 0 else math.log(1 + target_amount * monthly_return / monthly_savings) / math.log(1 + monthly_return)
            return f"🎯 Накопичите за {int(m_needed // 12)} років та {int(math.ceil(m_needed % 12))} місяців."
        elif months_available > 0 and monthly_savings == 0:
            req_monthly = target_amount / months_available if monthly_return == 0 else target_amount * monthly_return / ((1 + monthly_return)**months_available - 1)
            return f"🎯 Потрібно відкладати {req_monthly:.2f} грн щомісяця."
        return "Вкажіть АБО суму внеску, АБО термін (не обидва)."
    except Exception as e:
        return f"Помилка планування: {str(e)}"

@tool
def budget_analyzer(params: str) -> str:
    """Аналізує витрати за правилом 50/30/20.
    Action Input має бути рядком (через кому): дохід, витрати_на_житло, їжа, транспорт, інші_витрати.
    Приклад Action Input: 50000, 15000, 8000, 2000, 10000
    """
    logger.info(f"budget_analyzer отримав: {params}")
    try:
        parts = [p.strip() for p in params.split(',')]
        income = float(parts[0])
        housing = float(parts[1])
        food = float(parts[2])
        transport = float(parts[3])
        others = float(parts[4])

        needs_pct = ((housing + food + transport) / income) * 100
        wants_pct = (others / income) * 100
        savings_pct = ((income - (housing + food + transport + others)) / income) * 100
        ans = f"📊 Бюджет (50/30/20):\n- Потреби: {needs_pct:.1f}% (Норма: 50%)\n- Бажання: {wants_pct:.1f}% (Норма: 30%)\n- Заощадження: {savings_pct:.1f}% (Норма: 20%)\n"
        if needs_pct > 50: ans += "⚠️ Базові витрати зависокі.\n"
        if savings_pct < 0: ans += "🚨 КРИТИЧНО: Витрати перевищують дохід!"
        return ans
    except Exception as e:
        return f"Помилка аналізу: {str(e)}"

