prompt = PromptTemplate.from_template(system_template)
memory = ConversationBufferWindowMemory(k=5, memory_key="chat_history", return_messages=False)

agent = create_react_agent(llm, tools, prompt)
agent_executor = AgentExecutor(
    agent=agent,
    tools=tools,
    memory=memory,
    verbose=False,
    handle_parsing_errors="Будь ласка, переконайся, що Action Input передається як один рядок зі значеннями через кому.",
    max_iterations=20
)

